// Use initials when published minimum artwork sizes cannot fit.
const minimumLogoSizes: Readonly<Record<string, number>> = { walmart: 16 }

export function getServiceLogo(serviceId: string, artworkSize = Infinity): string | undefined {
  if (!Object.hasOwn(serviceLogos, serviceId)) return undefined
  if (artworkSize < (minimumLogoSizes[serviceId] ?? 0)) return undefined
  const asset = serviceLogos[serviceId]
  return asset ? `${import.meta.env.BASE_URL}logos/${asset}` : undefined
}
